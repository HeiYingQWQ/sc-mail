const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { classifyMail, extractAutomationDetails, shouldApplyAutomatedClassification, threadReferencesCampaign } = require('../dist/modules/mail/business-gate.rules.js');

assert.equal(shouldApplyAutomatedClassification(false), true);
assert.equal(shouldApplyAutomatedClassification(true), false);

const fixture = (name, direction = 'inbound') => {
  const rawSource = fs.readFileSync(path.resolve(`apps/backend/src/modules/mail/fixtures/${name}.eml`));
  const subject = rawSource.toString('utf8').match(/^Subject:\s*(.+)$/im)?.[1] ?? null;
  return { rawSource, direction, subject, fromJson: [], toJson: [] };
};

const business = fixture('business-human');
assert.equal(classifyMail(business).classification, 'BUSINESS_HUMAN');
assert.equal(classifyMail(business).reviewRequired, false);
assert.ok(classifyMail(business).evidence.some((item) => item.includes('Body phrase ignored')));
assert.equal(classifyMail(fixture('human-ticket-subject')).classification, 'BUSINESS_HUMAN');
assert.equal(classifyMail(fixture('human-alert-subject')).classification, 'BUSINESS_HUMAN');
assert.equal(classifyMail(fixture('newsletter')).classification, 'NEWSLETTER');
assert.equal(classifyMail(fixture('out-of-office')).classification, 'OUT_OF_OFFICE');
assert.equal(classifyMail(fixture('delivery-failure')).classification, 'DELIVERY_FAILURE');
const synthetic = (from, subject, extra = '', bodyText = 'body') => {
  const rawSource = Buffer.from(`From: ${from}\r\nTo: owner@example.test\r\nSubject: ${subject}\r\nMessage-ID: <synthetic@example.test>\r\n${extra}\r\n${bodyText}`);
  return { rawSource, bodyText, direction: 'inbound', subject, fromJson: [{ address: from.match(/[^<>\s]+@[^<>\s]+/)?.[0] ?? from }], toJson: [] };
};
assert.equal(classifyMail(synthetic('MAILER-DAEMON@zmail.test', 'Undelivered Mail Returned to Sender')).classification, 'DELIVERY_FAILURE');
assert.equal(classifyMail(synthetic('MAILER-DAEMON@zmail.test', 'failure notice 发送失败通知')).classification, 'DELIVERY_FAILURE');
assert.equal(classifyMail(synthetic('info@vendor.test', 'Automatic reply: Booth design')).classification, 'OUT_OF_OFFICE');
assert.equal(classifyMail(synthetic('customerservice@vendor.zendesk.com', 'Request received - Ticket 138359')).classification, 'TICKET_CONFIRMATION');
assert.equal(classifyMail(synthetic('no-reply@vendor.test', 'Unsubscribed successfully')).classification, 'UNSUBSCRIBE');
assert.equal(classifyMail(synthetic('no-reply@vendor.test', 'Wunderlich GmbH', '', 'Mit dieser automatisierten Antwort bestätigen wir den Eingang Ihrer Nachricht.')).classification, 'AUTO_ACKNOWLEDGEMENT');
assert.equal(classifyMail(synthetic('no-reply@vendor.test', 'Wunderlich GmbH', '', 'Haben Sie vielen Dank für Ihre Nachricht, deren Eingang wir Ihnen hiermit gerne bestätigen.')).classification, 'AUTO_ACKNOWLEDGEMENT');
assert.equal(classifyMail(synthetic('no-reply@vendor.test', 'Vielen Dank, dass Sie Formlabs kontaktiert haben', '', '')).classification, 'AUTO_ACKNOWLEDGEMENT');
assert.equal(classifyMail(synthetic('no-reply@vendor.test', 'REQUEST FOR QUOTATION', '', '')).classification, 'BUSINESS_HUMAN');
const oooMail = synthetic('person@vendor.test', 'Automatic reply: Annual leave', 'Auto-Submitted: auto-replied', 'I will be back on October 12, 2026.\nFor urgent matters, please contact Alex at alex@vendor.test or +39 02 12345678.');
const oooClass = classifyMail(oooMail);
assert.equal(oooClass.classification, 'OUT_OF_OFFICE');
const oooDetails = extractAutomationDetails(oooMail, oooClass.classification);
assert.ok(oooDetails.facts.some((fact) => fact.type === 'return_date_text' && fact.value === 'October 12, 2026'));
assert.ok(oooDetails.facts.some((fact) => fact.type === 'alternate_contact_email' && fact.value === 'alex@vendor.test'));
assert.ok(oooDetails.facts.some((fact) => fact.type === 'alternate_contact_phone'));
const ticketMail = synthetic('customerservice@vendor.zendesk.com', 'Request received - Ticket 138359', '', 'We created ticket #138359. Track it here: https://support.vendor.test/tickets/138359');
const ticketClass = classifyMail(ticketMail);
assert.equal(ticketClass.classification, 'TICKET_CONFIRMATION');
const ticketDetails = extractAutomationDetails(ticketMail, ticketClass.classification);
assert.ok(ticketDetails.facts.some((fact) => fact.type === 'ticket_id' && fact.value === '138359'));
assert.ok(ticketDetails.facts.some((fact) => fact.type === 'ticket_or_request_url'));
const bounceMail = synthetic('MAILER-DAEMON@zmail.test', 'Undelivered Mail Returned to Sender', '', 'Final-Recipient: rfc822; invalid@vendor.test\nDiagnostic-Code: smtp; 550 5.1.1 User unknown');
const bounceClass = classifyMail(bounceMail);
const bounceDetails = extractAutomationDetails(bounceMail, bounceClass.classification);
assert.ok(bounceDetails.facts.some((fact) => fact.type === 'recipient' && fact.value === 'invalid@vendor.test'));
assert.ok(bounceDetails.facts.some((fact) => fact.type === 'status_code' && fact.value === '5.1.1'));
assert.ok(bounceDetails.facts.some((fact) => fact.type === 'diagnostic'));
assert.deepEqual(extractAutomationDetails(business, 'BUSINESS_HUMAN'), {});
const phishing = classifyMail(synthetic('no-reply@vendor.test', 'Webmail Login Expired', '', 'Update your password now https://untrusted.example/login'));
assert.equal(phishing.classification, 'SPAM');
assert.equal(phishing.reviewRequired, true);
assert.equal(classifyMail(synthetic('news@vendor.test', 'Weekly offers', 'Precedence: bulk\r\nList-Unsubscribe: <mailto:unsubscribe@vendor.test>')).classification, 'MARKETING');
const authFailure = classifyMail(synthetic('notice@unexpected.test', 'Account notice', 'Authentication-Results: mx.test; dmarc=fail; spf=pass'));
assert.equal(authFailure.classification, 'SPAM');
assert.equal(authFailure.reviewRequired, true);
assert.equal(classifyMail(synthetic('client@customer.test', 'Re: mail delivery')).classification, 'BUSINESS_HUMAN');
const threadedHuman = synthetic('client@customer.test', 'Re: revised quotation', 'In-Reply-To: <external-smtp-send@example.test>\r\nReferences: <external-smtp-send@example.test>', 'Please revise the price by Friday.\n> Out of office until October 12.');
assert.equal(classifyMail(threadedHuman).classification, 'BUSINESS_HUMAN');
assert.deepEqual(extractAutomationDetails(threadedHuman, 'BUSINESS_HUMAN'), {});
assert.equal(classifyMail(synthetic('client@customer.test', '[Request received]')).classification, 'UNKNOWN');
assert.equal(classifyMail(fixture('outreach', 'outbound')).classification, 'OUTREACH_OUTBOUND');
assert.equal(threadReferencesCampaign(fixture('campaign-reply'), ['<campaign-1@example.test>']), true);
assert.equal(threadReferencesCampaign(fixture('campaign-reply'), ['<campaign-1@example.test.evil>']), false);
assert.equal(classifyMail(fixture('unknown-automated')).classification, 'UNKNOWN');
assert.equal(classifyMail(fixture('unknown-automated')).reviewRequired, true);
process.stdout.write('M4 Business Gate fixture checks passed\n');
